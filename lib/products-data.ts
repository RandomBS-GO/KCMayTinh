// Helper functions for filtering
export function getProductsByCategory(category: string): Product[] {
  if (category === 'all') return ALL_PRODUCTS;
  return ALL_PRODUCTS.filter((p) => p.category === category);
}

export function getFeaturedProducts(): Product[] {
  return ALL_PRODUCTS.filter((p) => p.featured).slice(0, 8);
}

export function getBestsellerProducts(): Product[] {
  return ALL_PRODUCTS.filter((p) => p.isBestseller).slice(0, 12);
}

export function getNewProducts(): Product[] {
  return ALL_PRODUCTS.filter((p) => p.isNewProduct).slice(0, 8);
}

export function getProductById(id: string): Product | undefined {
  return ALL_PRODUCTS.find((p) => p._id === id);
}

export function getProductBySlug(slug: string): Product | undefined {
  return ALL_PRODUCTS.find((p) => p.slug === slug);
}

export function getRelatedProducts(product: Product, limit = 4): Product[] {
  return ALL_PRODUCTS.filter(
    (p) => p._id !== product._id && (p.category === product.category || p.brand === product.brand)
  ).slice(0, limit);
}

export function searchProducts(query: string): Product[] {
  const q = query.toLowerCase();
  return ALL_PRODUCTS.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.brand.toLowerCase().includes(q) ||
      p.tags.some((t) => t.includes(q)) ||
      p.shortDescription.toLowerCase().includes(q)
  );
}
